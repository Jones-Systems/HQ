// Offline source generation only; never fetches data or runs in the application/tests.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const revision = '578f6c0516f5f268292ebda50b51848407a06478';
const source = `https://raw.githubusercontent.com/unicode-org/unicodetools/${revision}/unicodetools/data/ucd/15.1.0/CaseFolding.txt`;
const sha256 = '4e55acfdc32825a22e87670e9056a3bf94ad7c5400065778e9e10f8314372bcf';
if (process.argv.length !== 3) throw new Error('Usage: node generate-unicode-full-fold.mjs <CaseFolding.txt|->');
const input = readFileSync(process.argv[2] === '-' ? 0 : process.argv[2]);
if (createHash('sha256').update(input).digest('hex') !== sha256) throw new Error('Pinned Unicode 15.1.0 input SHA256 mismatch');

const mappings = new Map();
for (const line of input.toString('utf8').split('\n')) {
  const [code, status, mapping] = line.split('#')[0].split(';').map(field => field.trim());
  if (status !== 'C' && status !== 'F') continue;
  const scalar = Number.parseInt(code, 16);
  if (mappings.has(scalar)) throw new Error(`Duplicate full-fold mapping: ${code}`);
  mappings.set(scalar, mapping.split(' ').map(point => {
    const value = Number.parseInt(point, 16);
    return value <= 0xffff ? `\\u${value.toString(16).padStart(4, '0')}` : `\\u{${value.toString(16)}}`;
  }).join(''));
}
const rows = [...mappings].sort(([a], [b]) => a - b)
  .map(([scalar, folded]) => `  0x${scalar.toString(16)}: '${folded}',`);
const output = [
  '// Generated by generate-unicode-full-fold.mjs; do not edit.',
  '// Unicode 15.1.0 default full folding: C/F mappings only; S/T excluded.',
  '// Unlisted scalars are unchanged; concatenate mappings once without normalization.',
  '// © 2023 Unicode®, Inc. SPDX-License-Identifier: Unicode-3.0',
  '// Complete copyright and permission notice: unicode-LICENSE.txt.',
  `// Source: ${source}`,
  `// Input SHA256: ${sha256}`,
  `// Mapping count: ${mappings.size}. Provenance: unicode-full-fold.provenance.md.`,
  'export const UNICODE_FULL_FOLD: Readonly<Partial<Record<number, string>>> = {',
  ...rows,
  '};',
  '',
].join('\n');
writeFileSync(new URL('./unicode-full-fold.ts', import.meta.url), output);
console.log(`Generated ${mappings.size} Unicode 15.1.0 full-fold mappings; input SHA256 ${sha256}`);
