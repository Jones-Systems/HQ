// Offline source generation only; no network, runtime or test invocation.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const revision = '578f6c0516f5f268292ebda50b51848407a06478';
const source = `https://raw.githubusercontent.com/unicode-org/unicodetools/${revision}/unicodetools/data/ucd/15.1.0/extracted/DerivedGeneralCategory.txt`;
const sha256 = '760720ac034f96b630a3055879a744e0907184e8aa811e89ba34583a7a487e85';
if (process.argv.length !== 3) throw new Error('Usage: node generate-unicode-category-c.mjs <DerivedGeneralCategory.txt>');
const input = readFileSync(process.argv[2]);
if (createHash('sha256').update(input).digest('hex') !== sha256) throw new Error('Pinned Unicode 15.1.0 input SHA256 mismatch');

const categories = new Set('Lu Ll Lt Lm Lo Mn Me Mc Nd Nl No Zs Zl Zp Cc Cf Cs Co Cn Pd Ps Pe Pc Po Sm Sc Sk So Pi Pf'.split(' '));
const selected = new Set(['Cc', 'Cf', 'Cs', 'Co', 'Cn']);
const records = [];
const counts = Object.fromEntries([...selected].map(category => [category, 0]));
for (const [index, line] of input.toString('utf8').split('\n').entries()) {
  const data = line.split('#')[0].trim();
  if (!data) continue;
  const match = /^([0-9A-F]{4,6})(?:\.\.([0-9A-F]{4,6}))?\s*;\s*([A-Za-z]{2})$/.exec(data);
  if (!match || !categories.has(match[3])) throw new Error(`Malformed category record at line ${index + 1}`);
  const start = Number.parseInt(match[1], 16);
  const end = Number.parseInt(match[2] ?? match[1], 16);
  if (start > end || end > 0x10ffff) throw new Error(`Invalid category range at line ${index + 1}`);
  records.push({ start, end, category: match[3] });
}
records.sort((a, b) => a.start - b.start);
const ranges = [];
let next = 0;
for (const { start, end, category } of records) {
  // The derived file explicitly partitions every code point, including Cn and Cs.
  if (start !== next) throw new Error(`Overlapping or incomplete category input at U+${start.toString(16)}`);
  next = end + 1;
  if (!selected.has(category)) continue;
  counts[category] += end - start + 1;
  const last = ranges.at(-1);
  if (last && start === last[1] + 1) last[1] = end;
  else ranges.push([start, end]);
}
if (next !== 0x110000) throw new Error('Incomplete Unicode category input');
const codePoints = Object.values(counts).reduce((sum, count) => sum + count, 0);
const output = [
  '// Generated by generate-unicode-category-c.mjs; do not edit.',
  '// Unicode 15.1.0 category C: union of explicit Cc/Cf/Cs/Co/Cn records.',
  '// Sorted inclusive ranges, merged across adjacent selected records.',
  '// © 2023 Unicode®, Inc. SPDX-License-Identifier: Unicode-3.0',
  '// Complete copyright and permission notice: unicode-LICENSE.txt.',
  `// Source: ${source}`,
  `// Input SHA256: ${sha256}`,
  `// ${ranges.length} ranges; ${codePoints} code points; ${JSON.stringify(counts)}.`,
  '// Provenance and qualification limits: unicode-category-c.provenance.md.',
  'const CATEGORY_C_RANGES: readonly (readonly [number, number])[] = [',
  ...ranges.map(([start, end]) => `  [0x${start.toString(16)}, 0x${end.toString(16)}],`),
  '];',
  '',
  'export function containsUnicodeCategoryC(value: string): boolean {',
  '  for (const character of value) {',
  '    const codePoint = character.codePointAt(0)!;',
  '    let low = 0;',
  '    let high = CATEGORY_C_RANGES.length - 1;',
  '    while (low <= high) {',
  '      const middle = Math.floor((low + high) / 2);',
  '      const [start, end] = CATEGORY_C_RANGES[middle]!;',
  '      if (codePoint < start) high = middle - 1;',
  '      else if (codePoint > end) low = middle + 1;',
  '      else return true;',
  '    }',
  '  }',
  '  return false;',
  '}',
  '',
].join('\n');
writeFileSync(new URL('./unicode-category-c.ts', import.meta.url), output);
console.log(`Generated ${ranges.length} category-C ranges covering ${codePoints} code points: ${JSON.stringify(counts)}; input SHA256 ${sha256}`);
